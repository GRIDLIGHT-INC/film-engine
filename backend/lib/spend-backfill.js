/**
 * What a project spent BEFORE anything was tracking it.
 *
 * Metering starts the day it ships. Wingfall generated 34 storyboard frames,
 * 5 reference plates and 2 character sheets before any of this existed, and a
 * tracker that can only count forward reports $0.00 for all of it — which is
 * the same number it would report if nothing had ever been generated. The one
 * question the user actually asked ("how much has Wingfall cost me so far")
 * would be unanswerable on the day the answer became possible.
 *
 * So spend is reconstructed from what survives: the asset registry. Every row
 * in `film_assets` is a file that exists on disk because a provider was paid to
 * make it, and the project's own `provider_config` says which provider that
 * was. That is enough to price it.
 *
 * Three things this deliberately does NOT do, because each would produce a
 * number that looks authoritative and is wrong:
 *
 *   It does not count failed generations. A moderation refusal that walked the
 *   fallback chain cost real money and left no asset. The reconstruction is a
 *   FLOOR, and says so — better a defensible floor than an invented ceiling.
 *
 *   It does not guess durations it cannot read. A video asset's own
 *   `duration_ms` prices it; one without falls back to the shot's intended
 *   duration, and that substitution is recorded in `estimate_basis` rather
 *   than smoothed over.
 *
 *   It does not overwrite. Every reconstructed event carries a `source_ref` of
 *   the asset it was derived from, under a unique index, so running the
 *   backfill twice cannot double a project's history — which is exactly what a
 *   button labelled "reconstruct my spend" invites someone to do.
 *
 * Everything it writes is flagged `estimated = 1`, and the spend report totals
 * measured and estimated separately. "We measured $41" and "we think it was
 * about $41" are different claims, and only one of them should be defended.
 */

const { recordUsage } = require('./usage-meter');
const { rateFor } = require('./provider-pricing');

/**
 * Which capability produced each asset type.
 *
 * Types absent from this map were not generated by a paid provider — an FCPXML
 * export, a LUT, a subtitle file — and reconstructing a cost for them would
 * invent spend that never happened.
 */
const ASSET_CAPABILITY = {
    keyframe: 'image',
    storyboard: 'image',
    reference_image: 'image',
    character_sheet: 'image',
    thumbnail: 'image',
    video_raw: 'video',
    video_synced: 'lipsync',
    video_final: 'post',
    audio_dialogue: 'voice',
    audio_music: 'music',
    audio_sfx: 'sfx',
    audio_ambient: 'ambient',
    voice_sample: 'voice',
};

/** Asset types that exist without anyone paying a provider for them. */
const NOT_GENERATED = new Set([
    'subtitle', 'export_package', 'fcpxml', 'edl', 'premiere_xml', 'lut',
    'lora_weights', 'audio_mix', 'other',
]);

/**
 * Reconstruct one project's historical spend.
 *
 * @param {string} projectId
 * @param {object} [opts] - { dryRun: true } prices without writing.
 */
function backfillProject(projectId, opts = {}) {
    const { db } = require('../db/database');
    const { providerConfigFor } = require('./provider-config');

    const project = db.prepare('SELECT * FROM film_projects WHERE id = ?').get(projectId);
    if (!project) return null;

    const config = providerConfigFor(projectId);
    const { resolveId } = require('./providers');

    const assets = db.prepare(`
        SELECT a.*, sh.duration_ms AS shot_duration_ms, sh.scene_id AS shot_scene_id
        FROM film_assets a
        LEFT JOIN film_shots sh ON sh.id = a.shot_id
        WHERE a.project_id = ? ORDER BY a.created_at
    `).all(projectId);

    const already = new Set(
        db.prepare('SELECT source_ref FROM film_usage_events WHERE project_id = ? AND source_ref IS NOT NULL')
          .all(projectId).map(r => r.source_ref)
    );

    const recorded = [];
    const skipped = [];
    let total = 0;

    for (const asset of assets) {
        const sourceRef = `asset:${asset.id}`;
        if (already.has(sourceRef)) continue;

        if (NOT_GENERATED.has(asset.asset_type)) {
            skipped.push({ asset_id: asset.id, type: asset.asset_type, reason: 'not generated by a provider' });
            continue;
        }
        const capability = ASSET_CAPABILITY[asset.asset_type];
        if (!capability) {
            skipped.push({ asset_id: asset.id, type: asset.asset_type, reason: 'unknown asset type' });
            continue;
        }

        // Which provider made it. The asset's own metadata wins where it was
        // recorded; otherwise the project's current configuration is the best
        // available evidence — and being explicit that it is an assumption is
        // what keeps the number honest if a project switched providers midway.
        const meta = parseMeta(asset.metadata);
        const provider = meta.provider || resolveId(capability, config);
        const model = meta.model || meta.provider_model || '';

        const priced = quantityFor(capability, asset, provider, model);
        if (!priced) {
            skipped.push({ asset_id: asset.id, type: asset.asset_type, reason: 'no rate for this provider/capability' });
            continue;
        }

        const basis = [
            meta.provider ? 'provider recorded on the asset' : `provider assumed from the project's current config (${provider})`,
            priced.basis,
        ].filter(Boolean).join('; ');

        if (!opts.dryRun) {
            recordUsage({
                projectId,
                shotId: asset.shot_id || null,
                sceneId: asset.shot_scene_id || null,
                provider, capability, model: model || priced.model || '',
                unit: priced.unit, quantity: priced.quantity,
                estimated: true,
                estimate_basis: `reconstructed from film_assets — ${basis}`,
                sourceRef,
                latencyMs: 0,
            });
        }

        const rate = rateFor(provider, capability, model || priced.model);
        const usd = estimateUsd(rate, priced);
        total += usd;
        recorded.push({
            asset_id: asset.id, type: asset.asset_type, capability, provider,
            model: model || priced.model || '', unit: priced.unit,
            quantity: priced.quantity, usd: Math.round(usd * 1e4) / 1e4,
            created_at: asset.created_at,
        });
    }

    return {
        project_id: projectId,
        project_title: project.title,
        estimated: true,
        recorded: recorded.length,
        skipped: skipped.length,
        total_usd: Math.round(total * 100) / 100,
        entries: recorded,
        skipped_detail: skipped,
        floor: true,
        caveat: 'A floor, not a total. Generations that failed — a provider refusal, a run that errored before the file was registered — cost money and left no asset to count. Rates are today’s published rates applied to past work.',
    };
}

/** How much of the billing unit one asset represents. */
function quantityFor(capability, asset, provider, model) {
    const rate = rateFor(provider, capability, model);
    if (!rate) return null;

    switch (rate.unit) {
        case 'call':
        case 'image':
            return { unit: rate.unit, quantity: 1, basis: 'one generation per registered file' };

        case 'second': {
            const ms = Number(asset.duration_ms) || 0;
            if (ms > 0) return { unit: 'second', quantity: ms / 1000, basis: 'duration read from the file' };
            const shotMs = Number(asset.shot_duration_ms) || 0;
            if (shotMs > 0) return { unit: 'second', quantity: shotMs / 1000, basis: "file has no duration; used the shot's intended length" };
            return { unit: 'second', quantity: 5, basis: 'no duration anywhere; assumed 5s' };
        }

        case 'character': {
            // Dialogue length is what was billed, and the line is recoverable
            // from the shot's scene card — where it is not, a bare guess would
            // be worse than saying so.
            const chars = Number(asset.metadata && parseMeta(asset.metadata).characters) || 0;
            if (chars > 0) return { unit: 'character', quantity: chars, basis: 'character count recorded on the asset' };
            return { unit: 'character', quantity: 250, basis: 'no text recorded; assumed a 250-character line' };
        }

        case 'token':
            return null;   // LLM calls leave no asset; nothing to reconstruct from

        default:
            return null;
    }
}

function estimateUsd(rate, priced) {
    if (!rate) return 0;
    return (Number(priced.quantity) || 0) * (rate.usd_per_unit || 0);
}

function parseMeta(raw) {
    try { return JSON.parse(raw || '{}') || {}; } catch (_) { return {}; }
}

module.exports = { backfillProject, ASSET_CAPABILITY, NOT_GENERATED };
