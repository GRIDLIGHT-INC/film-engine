/**
 * What a director chose for THIS generation, rather than for the project.
 *
 * The quality tier is a project setting, which is the right default and the
 * wrong granularity for the moment that matters: someone looking at one frame
 * that came back badly wants to spend more on that frame, and someone trying
 * three compositions wants to spend less — neither wants to change a setting
 * and remember to put it back, which is how a whole board ends up shot on the
 * expensive tier because of one difficult shot.
 *
 * Read in ONE place because it is read by seven routes across four files, and
 * seven hand-written readings is how three of them come to accept `quality`
 * while a fourth silently ignores it.
 */

const { IMAGE_TIERS } = require('./quality-tiers');

/**
 * @param {object} body   the request body
 * @returns {object|null} a provider-config overlay, or null when nothing was asked
 */
function imageOverride(body) {
    const b = body || {};
    const out = {};

    const q = String(b.quality || '').toLowerCase();
    if (IMAGE_TIERS[q] || q === 'auto') out.image_quality = q;

    // The advanced escape hatch, per call. Validated against the provider by
    // withTierModel rather than here: a model only means anything relative to
    // one, and this function does not know which will run.
    if (typeof b.provider === 'string' && b.provider.trim()) out.image = b.provider.trim();
    if (typeof b.model === 'string' && b.model.trim()) out.image_model = b.model.trim().slice(0, 80);

    return Object.keys(out).length ? out : null;
}

/**
 * The prompt a director edited, or null.
 *
 * An override is the WHOLE prompt: nothing is appended after it, so a caller
 * sending back the unedited text would silently drop the references and the
 * style preset. That is the caller's decision to make deliberately, which is
 * why this only reads the field and never fills it in.
 */
function promptOverride(body) {
    const p = (body || {}).prompt_override;
    if (typeof p !== 'string') return null;
    const trimmed = p.trim();
    return trimmed ? trimmed : null;
}


/* ── One translator, every capability ────────────────────────────────────────
 *
 * WHY THIS REPLACES A PER-CAPABILITY ONE.
 *
 * `imageOverride` spoke in `image_*` keys, so routes/video-gen.js translated
 * them by hand -- and dropped `quality` doing it, because `image_quality` had
 * no `video_quality` counterpart there. Choosing a tier for a clip changed
 * nothing and said nothing. Music, ambient and 3D translated nothing at all:
 * their confirmations showed a prompt and offered no choice whatever.
 *
 * A translator written at each call site is how three of them came to disagree.
 * `resolve()` reads the capability's OWN key, so the mapping is mechanical and
 * belongs in one place.
 */

/**
 * The tier registry each capability ranks by, or null WITH A REASON.
 *
 * Named rather than omitted: "this capability has no tiers" and "we forgot to
 * wire the tiers" look identical from the outside, and only one is a decision.
 */
const TIERS_FOR = Object.freeze({
    image: () => require('./quality-tiers').IMAGE_TIERS,
    video: () => require('./video-tiers').VIDEO_TIERS,
    music: null,
    ambient: null,
    model3d: null,
});

const NO_TIER_NOTE = Object.freeze({
    music: 'Music has no quality tiers here — ElevenLabs prices a cue by its length, not by a '
        + 'model grade, so there is nothing to rank.',
    ambient: 'An ambient bed has no quality tiers — it is generated by the same model as a cue '
        + 'and priced by length.',
    model3d: 'Mesh generation has no quality tiers wired — Meshy grades by its own model choice, '
        + 'which is offered above as the model.',
});

const NO_SIZE_NOTE = Object.freeze({
    video: 'A clip\'s size is its provider tier — Seedance sells 480p/720p/1080p/4K as separate '
        + 'endpoints, and Runway takes a ratio rather than a raster. Choose it with the tier.',
    music: 'Audio has no raster.',
    ambient: 'Audio has no raster.',
    model3d: 'A mesh has no raster.',
});

function tiersOf(capability) {
    const entry = TIERS_FOR[capability];
    if (!entry) return null;
    try { return entry(); } catch (_) { return null; }
}

/**
 * What a director chose for THIS generation, as a provider-config overlay.
 *
 * Returns null when nothing was asked, so a caller that spreads it changes
 * nothing -- which is what keeps every existing generation byte-identical.
 */
function generationOverride(capability, body) {
    const cap = String(capability || '').trim();
    if (!cap) return null;
    const b = body || {};
    const out = {};

    if (typeof b.provider === 'string' && b.provider.trim()) out[cap] = b.provider.trim();
    if (typeof b.model === 'string' && b.model.trim()) {
        out[`${cap}_model`] = b.model.trim().slice(0, 80);
    }

    /*
     * A tier is checked against the capability's OWN registry. An invented one
     * used to travel to the resolver, match nothing, and generate at the
     * default while the dialog said otherwise -- a silent disagreement between
     * what was chosen and what ran.
     */
    const q = String(b.quality || '').toLowerCase();
    if (q) {
        const tiers = tiersOf(cap);
        if (tiers && (tiers[q] || q === 'auto')) out[`${cap}_quality`] = q;
    }

    /*
     * Size, for the capabilities that have a raster. A director trying one hero
     * frame at 2K should not have to change a project setting and change it
     * back -- and a size chosen here is for this generation only.
     */
    if (cap === 'image' && typeof b.size === 'string' && b.size.trim()) {
        const { RESOLUTIONS } = require('./project-presets');
        const found = RESOLUTIONS.find(r => r.id === b.size.trim());
        if (found) {
            out.image_size = found.id;
            out.width = found.width;
            out.height = found.height;
        }
    }

    return Object.keys(out).length ? out : null;
}

/**
 * What a dialog may offer for this capability.
 *
 * SERVED, never typed into the page -- the card-vocabulary rule. A page holding
 * its own list of providers or tiers offers choices the resolver refuses, and
 * the refusal reads as the generation being broken.
 *
 * An uncredentialed provider is LISTED AND MARKED, never hidden: hiding it
 * answers "which of these should I use" while withholding "and this one is
 * half the price if you sign up".
 */
/**
 * An adapter's models as one shape, whichever way it declares them.
 *
 * A label matters here: `gemini-3-pro-image` means nothing on a button, and
 * "Nano Banana Pro" is what a director asked for by name.
 */
function modelList(adapter, capability) {
    /*
     * Per capability, through the registry's one rule. This read a single flat
     * `adapter.models`, so an adapter serving two capabilities offered the same
     * menu to both -- Runway's image models under video, Meshy's under 3D.
     */
    let m = null;
    try { m = require('./providers').modelsFor(adapter, capability); }
    catch (_) { m = adapter && adapter.models; }
    if (!m) return null;
    if (Array.isArray(m)) {
        return m.map(x => (typeof x === 'string'
            ? { id: x, label: x }
            : { id: x.id || x.name, label: x.label || x.id || x.name, sizes: x.sizes || null }))
            .filter(x => x.id);
    }
    if (typeof m === 'object') {
        return Object.entries(m).map(([id, spec]) => ({
            id,
            label: (spec && (spec.label || spec.name)) || id,
            sizes: (spec && spec.sizes) || null,
        }));
    }
    return null;
}

function generationOptions(capability) {
    const cap = String(capability || '').trim();
    if (!cap) return null;

    let adapters = [];
    try {
        const providers = require('./providers');
        adapters = providers.list().filter(a => (a.capabilities || []).includes(cap));
    } catch (_) { adapters = []; }

    let isConfigured = () => false;
    try { isConfigured = require('./providers').isProviderConfigured; } catch (e) { console.error('[generation-override] optional module not available:', e.message); }

    const tiers = tiersOf(cap);

    let sizes = null;
    if (cap === 'image') {
        try {
            sizes = require('./project-presets').RESOLUTIONS
                .map(r => ({ id: r.id, label: r.label, width: r.width, height: r.height }));
        } catch (_) { sizes = null; }
    }

    return {
        capability: cap,
        providers: adapters.map(a => ({
            id: a.id,
            label: a.label || a.id,
            configured: (() => { try { return !!isConfigured(a.id); } catch (_) { return false; } })(),
            requires_key: a.requiresKey !== false,
            default_model: a.defaultModel || null,
            /*
             * NORMALISED, because adapters declare this two ways: Google holds
             * MODELS as an OBJECT keyed by id (so a typo is a refusal here
             * rather than a paid request that comes back as something else),
             * while others use a list. Assuming an array served Google's three
             * models as null, and Nano Banana Pro -- the only one of them that
             * a director would deliberately choose -- was unreachable.
             */
            models: (() => {
                const list = modelList(a, cap);
                if (!list || cap !== 'video') return list;
                // What each video model lets you choose, from the provider's own schema.
                const mo = require('./model-options');
                return list.map(m => {
                    const o = mo.optionsFor(a.id, m.id);
                    return o ? { ...m, options: o.controls, option_notes: o.notes } : m;
                });
            })(),
        })),
        tiers: tiers
            ? Object.entries(tiers).map(([id, t]) => ({
                id, label: (t && (t.label || t.purpose)) || id, purpose: (t && t.purpose) || null,
            }))
            : null,
        tiers_note: tiers ? null : (NO_TIER_NOTE[cap] || 'No quality tiers are defined for this capability.'),
        sizes,
        sizes_note: sizes ? null : (NO_SIZE_NOTE[cap] || 'This capability has no raster.'),
    };
}

module.exports = { imageOverride, promptOverride, generationOverride,
    generationOptions, TIERS_FOR, tiersOf };
