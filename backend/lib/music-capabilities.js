/**
 * THE MUSIC CAPABILITY REGISTRY (MUS-009).
 *
 * The engine had one music capability — a whole cue from a prompt — and the
 * workstation needs six ways of making music: compose a cue, generate its
 * native parts, separate a recording into stems, condition on a reference,
 * condition on the picture, regenerate a selected range. A provider serves
 * some and not others, and that difference is a FACT ABOUT THE PROVIDER
 * that has to be discoverable before anything spends: a workflow silently
 * unsupported is a button that fails at the provider with a message that
 * reads like a credential problem.
 *
 * THEY ARE WORKFLOWS OF THE `music` CAPABILITY, NOT SIX NEW CAPABILITIES.
 * A capability here is twelve registries — the cost gate, the canvas node
 * types, the taxonomy and interfaces manifests, the rate book, the readiness
 * brief, provider resolution, the settings payload, dry-run and four derived
 * test denominators — and five of these six have no provider serving them
 * today. Adding them there would put five nodes on the canvas and five rate
 * rows in the book describing things that do not exist, which is exactly the
 * `stock` mistake this codebase has already paid to undo. So each adapter
 * that serves `music` declares, per workflow, whether it is AVAILABLE,
 * PLANNED (the provider offers it, the adapter has not wired it — the next
 * task's work, named) or UNSUPPORTED, with its limits and a reason. Nothing
 * is inferred from silence: an adapter that serves music and declares no
 * contract fails the audit, and a contract that names a seventh workflow or
 * an unknown status fails the validator.
 *
 * "NO" IS AN ANSWER WITH A REASON. `unsupported()` is the one shape every
 * caller returns for a workflow the project's provider does not serve: the
 * workflow, the provider, its status, why, and who else could do it.
 *
 * THE SCHEMAS ARE NEUTRAL. A plan says what a person or an agent asks for in
 * the session's own terms — a session, a track, a length in milliseconds, a
 * range, an asset — never a provider's field names; each adapter translates.
 * A result is the outputs by kind, and every output kind lands as one of the
 * clip table's own `source_kind` values, held equal in both directions by
 * the test: a generated part, a separated stem and a rendered delivery stem
 * are three different things and must stay three words.
 */

const providers = require('./providers');
const pricing = require('./provider-pricing');
const contracts = require('./music-session');

/** What a workflow produces, and which clip source_kind it lands as. */
const OUTPUT_KINDS = Object.freeze({
    whole_cue: { what: 'one complete cue, mixed, as a single file', source_kind: 'generated' },
    native_part: { what: 'one instrument part of a cue, generated by the provider as its own file alongside the others', source_kind: 'native_part' },
    separated_stem: { what: 'one stem separated out of an existing recording — a derivative, never a new performance', source_kind: 'separated' },
    inpainted_range: { what: 'a selected range of an existing cue, regenerated in the context of what surrounds it', source_kind: 'generated' },
    rendered_stem: { what: 'a delivery stem bounced from the session itself, never from a provider', source_kind: 'rendered' },
    imported_file: { what: 'a file a composer handed over, stored byte-for-byte', source_kind: 'imported' },
});

/** What a provider may say about a workflow. */
const STATUSES = Object.freeze(['available', 'planned', 'unsupported']);

const F = (type, o) => ({ type, ...(o || {}) });

