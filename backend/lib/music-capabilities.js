// ── Contracts ──────────────────────────────────────────────────────────────

/** Hold an adapter's `music` declaration to the registry: exactly six workflows, a known status each, limits when available. */
function validateContract(providerId, contract) {
    const errors = [];
    const c = contract && typeof contract === 'object' ? contract : null;
    if (!c) return { ok: false, errors: [`${providerId}: no music contract`] };
    for (const wf of Object.keys(WORKFLOWS)) if (!c[wf]) errors.push(`${providerId}: ${wf} is not declared`);
    for (const [wf, decl] of Object.entries(c)) {
        if (!WORKFLOWS[wf]) { errors.push(`${providerId}: ${wf} is not a music workflow`); continue; }
        if (!decl || !STATUSES.includes(decl.status)) errors.push(`${providerId}.${wf}: status '${decl && decl.status}' is not one of ${STATUSES.join(', ')}`);
        if (decl && decl.status !== 'available' && !(decl.reason && String(decl.reason).length > 15)) errors.push(`${providerId}.${wf}: ${decl.status} with no reason`);
        if (decl && decl.status === 'available') {
            if (!decl.limits || typeof decl.limits !== 'object') errors.push(`${providerId}.${wf}: available with no limits`);
            else for (const f of WORKFLOWS[wf].limit_fields) if (decl.limits[f] === undefined) errors.push(`${providerId}.${wf}: available with no ${f} limit`);
            if (!decl.source) errors.push(`${providerId}.${wf}: available with no source for its limits`);
        }
    }
    return { ok: errors.length === 0, errors };
}

function contractOf(adapter) {
    if (!adapter || !(adapter.capabilities || []).includes('music')) return null;
    const v = validateContract(adapter.id, adapter.music);
    return v.ok ? adapter.music : null;
}

// ── Discovery ──────────────────────────────────────────────────────────────

/** A cost hint from the rate book, or an honest null with the reason. */
function costHint(providerId, wf, decl) {
    const unit = WORKFLOWS[wf].cost.unit;
    if (!decl || decl.status !== 'available') return { hint: null, note: `not priced: ${providerId} does not serve ${wf.replace('music_', '')} yet` };
    let rate = null;
    try { rate = pricing.rateFor(providerId, 'music', decl.default_model || null); } catch (_) { rate = null; }
    if (!rate) return { hint: null, note: `no rate in the book for ${providerId}:music` };
    if (rate.self_hosted || rate.subscription || !(rate.usd_per_unit > 0)) return { hint: null, note: `${providerId} bills nothing per ${unit} of music (${rate.self_hosted ? 'self-hosted' : rate.subscription ? 'subscription' : 'no rate'})` };
    if (rate.unit !== unit) return { hint: null, note: `no rate per ${unit}: ${providerId} is priced per ${rate.unit}` };
    return { hint: { unit, of: WORKFLOWS[wf].cost.of, usd_per_unit: rate.usd_per_unit, native_unit: rate.native_unit, native_per_unit: rate.native_per_unit,
        source: rate.source, checked: rate.checked, inferred: !!rate.inferred, note: rate.note || '' }, note: null };
}

/**
 * Every workflow, answered for the project's own music provider: status,
 * limits, cost hint, reason when not available, and which other providers
 * could. Spends nothing.
 */
function discoverMusicCapabilities(projectConfig) {
    const resolved = providers.resolveIdWithReason('music', projectConfig || {});
    // A pinned provider that cannot resolve today (the local gateway is opt-in
    // and off) is still the one the question is about: answer for it, and say
    // it did not resolve, rather than answering for nobody.
    const pinned = projectConfig && projectConfig.music ? String(projectConfig.music) : null;
    const providerId = resolved.id || pinned || null;
    const adapter = providers.get(providerId);
    const contract = contractOf(adapter);
    const servesMusic = !!(adapter && (adapter.capabilities || []).includes('music'));
    const all = providers.list().filter(a => contractOf(a));
    const workflows = Object.entries(WORKFLOWS).map(([wf, w]) => {
        const decl = contract ? contract[wf] : null;
        const status = decl ? decl.status : 'unsupported';
        const reason = decl ? (decl.reason || null)
            : !providerId ? 'no music provider is configured for this project'
                : servesMusic ? `${providerId} declares no music contract, so nothing can be assumed about ${wf.replace('music_', '')}`
                    : `${providerId} does not serve music at all`;
        const cost = costHint(providerId, wf, decl);
        return {
            workflow: wf, what: w.what, output_kind: w.output_kind, source_kind: OUTPUT_KINDS[w.output_kind].source_kind,
            status, supported: status === 'available', reason: status === 'available' ? null : reason,
            limits: decl && decl.limits ? decl.limits : null, models: decl && decl.models ? decl.models : null, source: decl && decl.source ? decl.source : null,
            cost_hint: cost.hint, cost_note: cost.note,
            alternatives: all.filter(a => a.id !== providerId && a.music[wf] && a.music[wf].status !== 'unsupported')
                .map(a => ({ id: a.id, status: a.music[wf].status, reason: a.music[wf].reason || null })),
            plan: w.plan, result: w.result,
        };
    });
    return {
        provider: { id: providerId, source: resolved.source, explicit: !!resolved.explicit, resolved: !!resolved.id, serves_music: servesMusic, has_contract: !!contract,
            note: resolved.id ? null : (providerId ? `${providerId} is pinned but does not resolve right now (${resolved.reason || resolved.source || 'not configured'})` : 'no music provider is configured') },
        workflows,
        output_kinds: OUTPUT_KINDS,
        statuses: STATUSES,
    };
}

/**
 * The explicit "no": null when the project's provider serves the workflow,
 * otherwise the one refusal shape every caller returns.
 */
function unsupported(workflow, projectConfig) {
    const out = discoverMusicCapabilities(projectConfig);
    const w = out.workflows.find(x => x.workflow === workflow);
    if (!w) return { ok: false, code: 'UNKNOWN_WORKFLOW', http_status: 400, workflow, error: `${workflow} is not a music workflow; the six are ${Object.keys(WORKFLOWS).join(', ')}` };
    if (w.supported) return null;
    const alt = w.alternatives.length ? ` Providers that could: ${w.alternatives.map(a => `${a.id} (${a.status})`).join(', ')}.` : ' No registered provider serves it.';
    return {
        ok: false, code: 'UNSUPPORTED', http_status: 409, workflow, provider: out.provider.id, status: w.status,
        error: `${out.provider.id} cannot ${workflow.replace('music_', '')} (${w.status}): ${w.reason}.${alt}`,
        reason: w.reason, alternatives: w.alternatives,
    };
}

// ── Plans ──────────────────────────────────────────────────────────────────

/**
 * A plan against its workflow's schema and the provider's declared limits.
 * Refuses with the field named — a request outside the provider's ceiling
 * is a paid failure, and the ceiling is known before anything is sent.
 */
function validatePlan(workflow, input, decl) {
    const w = WORKFLOWS[workflow];
    if (!w) return { ok: false, errors: [{ field: 'workflow', message: `${workflow} is not a music workflow` }] };
    const i = input || {};
    const limits = (decl && decl.limits) || {};
    const errors = [];
    const err = (field, message) => errors.push({ field, message });
    for (const [field, spec] of Object.entries(w.plan.fields)) {
        const v = i[field];
        const present = v !== undefined && v !== null && v !== '';
        if (spec.required && !present) { err(field, `${field} is required: ${spec.what || spec.type}`); continue; }
        if (!present) continue;
        if (spec.type === 'integer' && !(Number.isInteger(Number(v)) && Number(v) >= 0)) err(field, `${field} must be a whole non-negative number`);
        if (spec.type === 'number' && !Number.isFinite(Number(v))) err(field, `${field} must be a number`);
        if (spec.type === 'string' && typeof v !== 'string') err(field, `${field} must be text`);
        if (spec.type === 'array' && !Array.isArray(v)) err(field, `${field} must be a list`);
        if (spec.type === 'object' && (typeof v !== 'object' || Array.isArray(v))) err(field, `${field} must be an object`);
    }
    if (errors.length) return { ok: false, errors };

    if (i.duration_ms !== undefined && i.duration_ms !== null) {
        const d = Number(i.duration_ms);
        if (limits.min_ms !== undefined && d < limits.min_ms) err('duration_ms', `duration_ms ${d} is under the provider's min_ms ${limits.min_ms}`);
        if (limits.max_ms !== undefined && d > limits.max_ms) err('duration_ms', `duration_ms ${d} is over the provider's max_ms ${limits.max_ms}`);
    }
    if (i.model && Array.isArray(limits.models) && limits.models.length && !limits.models.includes(i.model)) err('model', `model ${i.model} is not one the provider offers: ${limits.models.join(', ')}`);
    if (workflow === 'music_parts' && Array.isArray(i.parts)) {
        if (limits.max_parts !== undefined && i.parts.length > limits.max_parts) err('parts', `${i.parts.length} parts is over the provider's max_parts ${limits.max_parts}`);
        if (Array.isArray(limits.part_roles) && limits.part_roles.length) {
            const bad = i.parts.filter(p => !limits.part_roles.includes(typeof p === 'string' ? p : p && p.role));
            if (bad.length) err('parts', `parts the provider cannot generate: ${bad.map(p => typeof p === 'string' ? p : p && p.role).join(', ')} (it offers ${limits.part_roles.join(', ')})`);
        }
    }
    if (workflow === 'music_separate' && Array.isArray(limits.stem_counts) && limits.stem_counts.length && !limits.stem_counts.includes(Number(i.stems))) {
        err('stems', `stems must be one of ${limits.stem_counts.join(', ')} on this provider`);
    }
    if (workflow === 'music_reference' && Array.isArray(limits.reference_kinds) && limits.reference_kinds.length && !limits.reference_kinds.includes(i.reference_kind)) {
        err('reference_kind', `reference_kind must be one of ${limits.reference_kinds.join(', ')} on this provider`);
    }
    if (workflow === 'music_inpaint' && i.range) {
        const s = Number(i.range.start_ms), e = Number(i.range.end_ms);
        if (!(Number.isInteger(s) && Number.isInteger(e) && s >= 0 && e > s)) err('range', 'range must be { start_ms, end_ms } with end_ms after start_ms');
        else if (limits.max_range_ms !== undefined && e - s > limits.max_range_ms) err('range', `the range (${e - s} ms) is over the provider's max_range_ms ${limits.max_range_ms}`);
    }
    return { ok: errors.length === 0, errors };
}

module.exports = { WORKFLOWS, OUTPUT_KINDS, STATUSES, MUSIC_CALL_SITES, validateContract, contractOf, discoverMusicCapabilities, unsupported, validatePlan, costHint };
